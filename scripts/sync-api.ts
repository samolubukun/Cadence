/**
 * Fetches the OpenAPI spec from the Cadence Audio Engine API and generates TypeScript types.
 *
 * Usage:
 *   CADENCE_API_URL=https://your-api-url npm run sync-api
 *
 * Or with .env file:
 *   npm run sync-api
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import dotenv from "dotenv";
import openapiTS, { astToString } from "openapi-typescript";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
dotenv.config({ path: path.resolve(__dirname, "../.env.local") });
dotenv.config({ path: path.resolve(__dirname, "../.env") });

const OUTPUT_PATH = path.resolve(__dirname, "../src/types/cadence-api.d.ts");
const LEGACY_OUTPUT_PATH = path.resolve(__dirname, "../src/types/chatterbox-api.d.ts");

async function main() {
  const apiUrl = process.env.CADENCE_API_URL;

  if (!apiUrl) {
    console.error("Error: CADENCE_API_URL environment variable is required");
    process.exit(1);
  }

  const openApiUrl = `${apiUrl}/openapi.json`;
  console.log(`Fetching OpenAPI spec from: ${openApiUrl}`);

  const ast = await openapiTS(new URL(openApiUrl));
  const contents = astToString(ast);

  // Ensure output directory exists
  const outputDir = path.dirname(OUTPUT_PATH);
  if (!fs.existsSync(outputDir)) {
    fs.mkdirSync(outputDir, { recursive: true });
  }

  // Add header comment
  const header = `/**
* This file is auto-generated by scripts/sync-api.ts
* Do not edit manually. Run \`npm run sync-api\` to regenerate.
*
* Generated from: ${openApiUrl}
* Generated at: ${new Date().toISOString()}
*/
  `;

  fs.writeFileSync(OUTPUT_PATH, header + contents);
  console.log(`Types written to: ${OUTPUT_PATH}`);

  // Maintain legacy re-export file
  const legacyContent = `/**
 * Legacy compatibility alias for Cadence API types.
 * Prefer importing from "@/types/cadence-api".
 */
export * from "./cadence-api";
`;
  fs.writeFileSync(LEGACY_OUTPUT_PATH, legacyContent);
}

main().catch((err) => {
  console.error("Failed to sync API types:", err);
  process.exit(1);
});
